/** 根据累计收益与粉丝，计算在某平台的当前作家等级与下一级信息 */
export function getPlatformAuthorRank(
  platformId: NovelPlatformId,
  totalRevenue: number,
  totalFans: number,
): {
  currentRank: import('../types/platform').PlatformAuthorRank
  nextRank: import('../types/platform').PlatformAuthorRank | null
  progressToNext: number
} {
  const platform = PLATFORMS[platformId]
  const ranks = platform.authorRanks
  let currentRank = ranks[0]
  let nextRank: import('../types/platform').PlatformAuthorRank | null = null

  for (let i = 0; i < ranks.length; i++) {
    const rank = ranks[i]
    if (totalRevenue >= rank.revenueThreshold && totalFans >= rank.fanThreshold) {
      currentRank = rank
      nextRank = ranks[i + 1] ?? null
    } else {
      break
    }
  }

  let progressToNext = 0
  if (nextRank) {
    const revenueProgress = Math.min(
      1,
      Math.max(
        0,
        (totalRevenue - currentRank.revenueThreshold) /
          (nextRank.revenueThreshold - currentRank.revenueThreshold),
      ),
    )
    const fanProgress = Math.min(
      1,
      Math.max(
        0,
        (totalFans - currentRank.fanThreshold) /
          (nextRank.fanThreshold - currentRank.fanThreshold),
      ),
    )
    progressToNext = Math.min(revenueProgress, fanProgress)
  }

  return { currentRank, nextRank, progressToNext }
}
